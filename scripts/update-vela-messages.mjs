for (const loc of locales) {
  const filePath = path.join(messagesDir, `${loc}.json`);
  if (!fs.existsSync(filePath)) continue;
  const content = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  
  // Ensure Navigation.vela exists
  if (!content.Navigation) content.Navigation = {};
  content.Navigation.vela = velaTranslations[loc]?.navVela || "VELA";

  // Add Vela namespace
  content.Vela = velaTranslations[loc] || velaTranslations.en;

  fs.writeFileSync(filePath, JSON.stringify(content, null, 2), 'utf-8');
  console.log(`Updated messages for ${loc}`);
}
